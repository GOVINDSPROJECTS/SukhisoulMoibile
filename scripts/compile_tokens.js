const fs = require('fs');
const path = require('path');

const colorPath = path.join(__dirname, '..', 'Required', 'Color 3', 'Mode 1.tokens.json');
const typoPath = path.join(__dirname, '..', 'Required', 'Typography 1', 'Mode 1.tokens.json');
const valuePath = path.join(__dirname, '..', 'Required', 'Value 2', 'Mode 1.tokens.json');
const outputPath = path.join(__dirname, '..', 'src', 'theme', 'tokens.ts');

// Utility to helper parse leaf tokens
function getLeafTokens(obj, prefix = '') {
  let results = {};
  if (obj && typeof obj === 'object') {
    if (obj.hasOwnProperty('$value')) {
      results[prefix.slice(0, -1)] = obj['$value'];
    } else {
      for (const key of Object.keys(obj)) {
        if (key.startsWith('$')) continue;
        Object.assign(results, getLeafTokens(obj[key], prefix + key + '.'));
      }
    }
  }
  return results;
}

// Convert string key to valid JS camelCase identifier name
function toCamelCase(str) {
  return str
    .replace(/[^a-zA-Z0-9 ]/g, '')
    .split(' ')
    .map((word, index) => {
      if (index === 0) return word.toLowerCase();
      return word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();
    })
    .join('');
}

function processColors(leaves) {
  const colors = {};

  for (const [key, value] of Object.entries(leaves)) {
    // Expected keys: color.App Theme Color.50 or Color.Dark blue
    const parts = key.split('.');
    let hex = value;
    if (typeof value === 'object' && value.hex) {
      hex = value.hex;
    }

    if (parts[0] === 'color') {
      const category = toCamelCase(parts[1]);
      if (!colors[category]) {
        colors[category] = {};
      }

      if (parts.length === 3) {
        // e.g. color.App Theme Color.50
        const subkey = parts[2].trim();
        colors[category][subkey] = hex;
      } else if (parts.length === 4) {
        // e.g. color.Light Tints.Red light tint.50
        const subCat = toCamelCase(parts[2]);
        if (!colors[category][subCat]) {
          colors[category][subCat] = {};
        }
        const subkey = parts[3].trim();
        colors[category][subCat][subkey] = hex;
      }
    } else if (parts[0] === 'Color') {
      const category = toCamelCase(parts[0]);
      if (!colors[category]) {
        colors[category] = {};
      }
      const subkey = toCamelCase(parts[1]);
      colors[category][subkey] = hex;
    }
  }

  return colors;
}

function processSpacingAndSizes(leaves) {
  const spacing = {};
  const sizes = {};

  for (const [key, value] of Object.entries(leaves)) {
    const parts = key.split('.');
    if (parts[0] === 'spacing') {
      // Map name
      let subkey = parts[1];
      // Sanitize key names for spacing (e.g. 'neg 0 5' -> 'neg_0_5')
      subkey = subkey.replace(/ /g, '_');
      spacing[subkey] = value;
    } else if (parts[0] === 'sizes') {
      let subkey = parts[1];
      subkey = subkey.replace(/ /g, '_');
      sizes[subkey] = value;
    }
  }

  return { spacing, sizes };
}

function processTypography(typoLeaves) {
  // Extract values
  const typography = {
    fontFamilies: {
      primary: typoLeaves['Font.Font family'] || 'Manrope',
      secondary: typoLeaves['Font.Font family 2'] || 'DMSans',
    },
    weights: {
      light: typoLeaves['Light'] || 'Light',
      regular: typoLeaves['Regular'] || 'Regular',
      medium: typoLeaves['Medium'] || 'Medium',
      semibold: typoLeaves['Semibond'] || 'Semibold',
      bold: typoLeaves['Bold'] || 'Bold',
      black: typoLeaves['Black'] || 'Black',
      extraBold: typoLeaves['Black 2'] || 'ExtraBold',
    }
  };
  return typography;
}

function generateTS() {
  const colorData = getLeafTokens(JSON.parse(fs.readFileSync(colorPath, 'utf8')));
  const typoData = getLeafTokens(JSON.parse(fs.readFileSync(typoPath, 'utf8')));
  const valueData = getLeafTokens(JSON.parse(fs.readFileSync(valuePath, 'utf8')));

  const colors = processColors(colorData);
  const { spacing, sizes } = processSpacingAndSizes(valueData);
  const typography = processTypography(typoData);

  const fileContent = `/**
 * Automatically generated design tokens from Figma tokens files in the 'Required' directory.
 * Do not edit this file directly.
 */

export const colorTokens = ${JSON.stringify(colors, null, 2)} as const;

export const spacingTokens = ${JSON.stringify(spacing, null, 2)} as const;

export const sizeTokens = ${JSON.stringify(sizes, null, 2)} as const;

export const typographyTokens = ${JSON.stringify(typography, null, 2)} as const;
`;

  // Make sure output folder exists
  const dir = path.dirname(outputPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  fs.writeFileSync(outputPath, fileContent);
  console.log(`Successfully compiled design tokens to: ${outputPath}`);
}

generateTS();
